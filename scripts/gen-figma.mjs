#!/usr/bin/env node
// Builds the Figma plugin (packages/figma/dist/code.js): the token build inlined ahead of the plugin source, so the
// library it draws has the same values as the CSS. Run `pnpm figma` after `pnpm tokens`; `--check` fails if stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (path) => readFileSync(join(root, path), 'utf8');

export function buildFigmaPlugin() {
  const tokens = JSON.parse(read('packages/tokens/dist/tokens.json'));
  const source = read('packages/figma/src/plugin.js');
  // Figma runs plugins in its own JavaScript sandbox, which has rejected newer syntax (?., ??, object spread) at
  // parse time. The source is written in today's JavaScript and compiled down to ES2017 here, so nothing depends on
  // which version of the sandbox a file is opened in.
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { target: ts.ScriptTarget.ES2017, module: ts.ModuleKind.None, allowJs: true },
  });
  return [
    '// Generated by scripts/gen-figma.mjs from packages/figma/src/plugin.js and the token build. Do not edit.',
    `var DTHEO_TOKENS = ${JSON.stringify(tokens)};`,
    outputText,
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = join(root, 'packages/figma/dist/code.js');
  const code = buildFigmaPlugin();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(out, 'utf8');
    } catch {}
    if (current !== code) {
      console.error('packages/figma/dist/code.js is stale. Run `pnpm figma`.');
      process.exit(1);
    }
    console.log('Figma plugin is current.');
  } else {
    writeFileSync(out, code);
    console.log(`packages/figma/dist/code.js: ${Math.round(code.length / 1024)} KB.`);
  }
}
