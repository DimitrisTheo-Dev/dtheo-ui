#!/usr/bin/env node
// Regenerates apps/docs/examples/index.ts from the example files on disk, and reports contract examples
// that have no file yet. Run after adding an example: `node scripts/gen-examples.mjs`.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'apps/docs/examples');
const files = readdirSync(dir)
  .filter((f) => f.endsWith('.tsx'))
  .map((f) => f.replace(/\.tsx$/, ''))
  .sort();

const ident = (id) => id.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase()).replace(/^(\d)/, '_$1');
const out = `'use client';

// Generated by scripts/gen-examples.mjs. Do not edit by hand.
import type * as React from 'react';
${files.map((id) => `import ${ident(id)} from './${id}';`).join('\n')}

/** Every example rendered on a docs page, keyed by the id used in the component contract. */
export const examples: Record<string, React.ComponentType> = {
${files.map((id) => `  '${id}': ${ident(id)},`).join('\n')}
};
`;
writeFileSync(join(dir, 'index.ts'), out);

const meta = readFileSync(join(root, 'packages/ui/src/meta/index.ts'), 'utf8');
const wanted = [...meta.matchAll(/examples: \[([^\]]*)\]/g)].flatMap((m) =>
  [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1]),
);
const missing = wanted.filter((id) => !files.includes(id));
console.log(`examples/index.ts: ${files.length} examples registered.`);
if (missing.length)
  console.log(`Contract examples without a file (${missing.length}): ${missing.join(', ')}`);
