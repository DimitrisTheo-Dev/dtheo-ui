#!/usr/bin/env node
// Regenerates apps/docs/lib/usage-data.ts, the "Used in" graph, from what each page actually imports.
// Run after changing an example or pattern: `node scripts/gen-usage.mjs`. `--check` fails if the file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (path) => readFileSync(join(root, path), 'utf8');

// Every Actuator Lab tool renders the shared sidebar and the shared ⌘K palette.
const lab = ['apps/docs/app/examples/_shared/lab-sidebar.tsx', 'apps/docs/app/examples/_shared/lab-palette.tsx'];

const pages = [
  {
    id: 'run-review',
    title: 'Run review',
    href: '/examples/run-review',
    level: 'page',
    sources: ['apps/docs/app/examples/run-review/run-review.tsx', ...lab],
  },
  {
    id: 'motor-map',
    title: 'Motor map',
    href: '/examples/motor-map',
    level: 'page',
    sources: ['apps/docs/app/examples/motor-map/motor-map.tsx', ...lab],
  },
  {
    id: 'tuning',
    title: 'Loop tuning',
    href: '/examples/tuning',
    level: 'page',
    sources: ['apps/docs/app/examples/tuning/tuning.tsx', ...lab],
  },
  {
    id: 'assistant',
    title: 'Lab assistant',
    href: '/examples/assistant',
    level: 'page',
    sources: ['apps/docs/app/examples/assistant/assistant.tsx', ...lab],
  },
  {
    id: 'home',
    title: 'Home page',
    href: '/',
    level: 'page',
    sources: ['apps/docs/app/(site)/page.tsx', 'apps/docs/components/home/hero-preview.tsx'],
  },
  {
    id: 'data-table',
    title: 'Data table pattern',
    href: '/docs/patterns/data-table',
    level: 'template',
    sources: ['apps/docs/components/patterns/data-table-demo.tsx'],
  },
  {
    id: 'forms',
    title: 'Forms pattern',
    href: '/docs/patterns/forms',
    level: 'template',
    sources: ['apps/docs/components/patterns/form-demo.tsx'],
  },
  {
    id: 'states',
    title: 'States pattern',
    href: '/docs/patterns/states',
    level: 'template',
    sources: ['apps/docs/components/patterns/states-demo.tsx'],
  },
];

// Contract entries: slug, files and exports, read from the meta source so this script needs no build.
const meta = read('packages/ui/src/meta/index.ts');
const entries = [
  ...meta.matchAll(/slug: '([\w-]+)'[\s\S]*?files: \[([^\]]*)\][\s\S]*?exports: \[([^\]]*)\]/g),
].map((m) => ({
  slug: m[1],
  files: [...m[2].matchAll(/'([^']+)'/g)].map((f) => f[1]),
  exports: [...m[3].matchAll(/'([^']+)'/g)].map((e) => e[1]),
}));
const order = entries.map((e) => e.slug);
const bySlugFile = (file) =>
  entries.find((e) => `components/${e.slug}.tsx` === file) ?? entries.find((e) => e.files.includes(file));

function uses(sources) {
  const src = sources.map(read).join('\n');
  const found = new Set();
  for (const m of src.matchAll(/@dtheo\/ui\/components\/([\w-]+)'/g)) {
    const entry = bySlugFile(`components/${m[1]}.tsx`);
    if (entry) found.add(entry.slug);
  }
  for (const m of src.matchAll(/import \{([^}]*)\} from '@dtheo\/charts'/g)) {
    for (const name of m[1]
      .split(',')
      .map((s) => s.replace(/^type\s+/, '').trim())
      .filter(Boolean)) {
      const entry = entries.find((e) => e.exports.includes(name));
      if (entry) found.add(entry.slug);
    }
  }
  return [...found].sort((a, b) => order.indexOf(a) - order.indexOf(b));
}

const body = pages
  .map((p) => {
    const list = uses(p.sources)
      .map((s) => `'${s}'`)
      .join(', ');
    return `  '${p.id}': {\n    title: '${p.title}',\n    href: '${p.href}',\n    level: '${p.level}',\n    uses: [${list}],\n  },`;
  })
  .join('\n');

const out = `// Generated by scripts/gen-usage.mjs from each page's imports. Do not edit by hand.

export type PageUsage = { title: string; href: string; level: 'template' | 'page'; uses: string[] };

export const pageUsage: Record<string, PageUsage> = {
${body}
};
`;

const target = join(root, 'apps/docs/lib/usage-data.ts');
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {}
  if (current !== out) {
    console.error('apps/docs/lib/usage-data.ts is stale. Run: node scripts/gen-usage.mjs');
    process.exitCode = 1;
  } else console.log('Usage graph is current.');
} else {
  writeFileSync(target, out);
  console.log(`usage-data.ts: ${pages.length} pages.`);
}
