// dtheo-check-disable-file raw-color -- the token build writes the color values.
/**
 * Builds every token output from src/index.ts and verifies contrast.
 *   pnpm tokens         write outputs, fail on contrast violations
 *   pnpm tokens:check   verify only (CI), fail if outputs are stale or contrast fails
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { converter, formatHex, parse, toGamut, wcagContrast, type Oklch, type Rgb } from 'culori';
import {
  colorRoles,
  contrastPairs,
  foundation,
  pairLabel,
  presets,
  type ColorScheme,
  type Mode,
} from '../src/index';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');
const checkOnly = process.argv.includes('--check');

const toRgb = converter('rgb');
const clampRgb = toGamut('rgb', 'oklch');

function rgba(value: string): Rgb {
  const c = toRgb(value);
  if (!c) throw new Error(`Unparseable color: ${value}`);
  return clampRgb(c) as Rgb;
}

/** Source-over composite in sRGB, like the browser does. */
function over(top: Rgb, bottom: Rgb): Rgb {
  const a = top.alpha ?? 1;
  const b = bottom.alpha ?? 1;
  if (b < 1) throw new Error('Bottom layer must be opaque');
  return {
    mode: 'rgb',
    r: top.r * a + bottom.r * (1 - a),
    g: top.g * a + bottom.g * (1 - a),
    b: top.b * a + bottom.b * (1 - a),
  };
}

function resolveSurface(scheme: ColorScheme, role: keyof ColorScheme, under?: keyof ColorScheme): Rgb {
  const c = rgba(scheme[role]);
  if ((c.alpha ?? 1) >= 1) return c;
  const base = under ? resolveSurface(scheme, under) : rgba(scheme.background);
  return over(c, base);
}

/** Composite a stack of surfaces bottom-up on the page background: [top, …, bottom]. `tint` overrides the top's alpha. */
function resolveStack(scheme: ColorScheme, layers: (keyof ColorScheme)[], tint?: number): Rgb {
  let acc = rgba(scheme.background);
  layers.toReversed().forEach((role, i, all) => {
    const c = rgba(scheme[role]);
    const top = i === all.length - 1 && tint !== undefined ? { ...c, alpha: (c.alpha ?? 1) * tint } : c;
    acc = (top.alpha ?? 1) >= 1 ? top : over(top, acc);
  });
  return acc;
}

// ---------- Contrast verification ----------
type Row = {
  preset: string;
  mode: Mode;
  /** Position in contrastPairs: labels can repeat (the ring against its halo on several surfaces). */
  index: number;
  pair: string;
  ratio: number;
  min: number;
  ok: boolean;
  note: string;
};
const rows: Row[] = [];
for (const preset of presets) {
  for (const [mode, scheme] of Object.entries(preset.modes) as [Mode, ColorScheme][]) {
    for (const [index, p] of contrastPairs.entries()) {
      if (p.modes && !p.modes.includes(mode)) continue;
      const bg =
        Array.isArray(p.over) || p.tint !== undefined
          ? resolveStack(scheme, [p.bg, ...(Array.isArray(p.over) ? p.over : p.over ? [p.over] : [])], p.tint)
          : resolveSurface(scheme, p.bg, p.over);
      const fgRaw = p.fg === 'white' ? rgba('oklch(1 0 0)') : rgba(scheme[p.fg]);
      const fg = (fgRaw.alpha ?? 1) < 1 ? over(fgRaw, bg) : fgRaw;
      const ratio = wcagContrast(fg, bg);
      rows.push({
        preset: preset.id,
        mode,
        index,
        pair: pairLabel(p),
        ratio,
        min: p.min,
        ok: ratio >= p.min,
        note: p.note,
      });
    }
  }
}
const failures = rows.filter((r) => !r.ok);
for (const row of rows.filter((r) => r.preset === 'graphite')) {
  console.log(
    `${row.ok ? 'ok  ' : 'FAIL'} ${row.preset}/${row.mode.padEnd(5)} ${row.pair.padEnd(42)} ${row.ratio.toFixed(2)} (min ${row.min})`,
  );
}
// Every pair is measured in every theme (preset and mode), so the total counts checks: pairs × themes.
const themes = presets.reduce((n, p) => n + Object.keys(p.modes).length, 0);
console.log(
  `\n${rows.length - failures.length}/${rows.length} contrast checks pass: ${contrastPairs.length} pairs in ${themes} themes (${presets.length} presets).`,
);
if (failures.length) {
  console.error('\nContrast failures:');
  for (const f of failures)
    console.error(`  ${f.preset}/${f.mode} ${f.pair}: ${f.ratio.toFixed(2)} < ${f.min} (${f.note})`);
}

// ---------- CSS ----------
const lines: string[] = [];
const decl = (k: string, v: string) => `  --${k}: ${v};`;
const header = `/* Generated by @dtheo/tokens from packages/tokens/src/index.ts. Do not edit by hand; run \`pnpm tokens\`. */`;

const graphite = presets[0]!;
const base: string[] = [];
base.push(decl('font-sans', foundation.font.sans), decl('font-mono', foundation.font.mono));
for (const [k, v] of Object.entries(foundation.ease)) base.push(decl(`ease-${k}`, v));
for (const [k, v] of Object.entries(foundation.duration)) base.push(decl(`duration-${k}`, v));
for (const [k, v] of Object.entries(foundation.control)) base.push(decl(`control-${k}`, v));
for (const [k, v] of Object.entries(foundation.text)) {
  base.push(
    decl(`text-${k}`, v[0]),
    decl(`text-${k}--line-height`, v[1]),
    decl(`text-${k}--letter-spacing`, v[2]),
    decl(`text-${k}--font-weight`, v[3]),
  );
}
for (const [k, v] of Object.entries(graphite.geometry)) base.push(decl(k, v));

const colorBlock = (scheme: ColorScheme) => colorRoles.map((r) => decl(r, scheme[r]));
const shadowBlock = (mode: Mode) =>
  Object.entries(foundation.shadow[mode]).map(([k, v]) => decl(`shadow-${k}`, v));

// Everything that is not a color is declared once, on the root. A mode class further down the tree changes colors
// and shadows only, so a light scope inside a preset keeps that preset's corners, and on a touch screen its sizes.
lines.push(header, '', ':root {', ...base, '}', '');
lines.push(
  ':root,',
  '.light {',
  ...colorBlock(graphite.modes.light!),
  ...shadowBlock('light'),
  '  color-scheme: light;',
  '}',
  '',
);
lines.push(
  '.dark {',
  ...colorBlock(graphite.modes.dark!),
  ...shadowBlock('dark'),
  '  color-scheme: dark;',
  '}',
  '',
);
// On touch screens the default control grows to a 36px target, and lg stays one step above it.
lines.push(
  '@media (pointer: coarse) {',
  '  :root {',
  `    --control-md: ${foundation.control.touch};`,
  `    --control-lg: calc(${foundation.control.touch} + 4px);`,
  '  }',
  '}',
  '',
);

// A preset takes its mode from the nearest mode above it, or from its own element, or gives it to one inside it.
// Light is the plain attribute selector. Dark is more specific, so a preset with no mode class follows a dark page;
// a light scope between that page and the preset is more specific again, so the nearer of the two wins. CSS can only
// spell out so many levels: three scopes deep, put the mode on the preset's own element, as ThemeScope does.
for (const preset of presets.slice(1)) {
  const sel = `[data-preset="${preset.id}"]`;
  lines.push(`${sel} {`, ...Object.entries(preset.geometry).map(([k, v]) => decl(k, v)), '}', '');
  const light = preset.modes.light;
  if (light)
    lines.push(
      `${sel},`,
      `.light${sel},`,
      `${sel} .light,`,
      `.dark .light ${sel}:not(.dark) {`,
      ...colorBlock(light),
      '}',
      '',
    );
  const dark = preset.modes.dark;
  if (dark)
    lines.push(`.dark ${sel}:not(.light),`, `.dark${sel},`, `${sel} .dark {`, ...colorBlock(dark), '}', '');
}
const css = lines.join('\n');

// ---------- Tailwind v4 theme ----------
// Static defaults live in @theme (Tailwind's layer); tokens.css re-declares them unlayered per preset/mode, which wins.
const themeLines: string[] = [
  header,
  '@custom-variant dark (&:where(.dark, .dark *));',
  '',
  '@theme {',
  '  --color-*: initial;',
  '  --color-white: oklch(1 0 0);',
  '  --color-black: oklch(0 0 0);',
  decl('font-sans', foundation.font.sans),
  decl('font-mono', foundation.font.mono),
  ...Object.entries(foundation.text).flatMap(([k, v]) => [
    decl(`text-${k}`, v[0]),
    decl(`text-${k}--line-height`, v[1]),
    decl(`text-${k}--letter-spacing`, v[2]),
    decl(`text-${k}--font-weight`, v[3]),
  ]),
  ...Object.entries(foundation.ease).map(([k, v]) => decl(`ease-${k}`, v)),
  ...Object.entries(graphite.geometry)
    .filter(([k]) => k.startsWith('radius'))
    .map(([k, v]) => decl(k, v)),
  ...Object.entries(foundation.shadow.light).map(([k, v]) => decl(`shadow-${k}`, v)),
  '}',
  '',
  '@theme inline {',
  ...colorRoles.map((r) => decl(`color-${r}`, `var(--${r})`)),
  ...Object.keys(foundation.control).map((k) => decl(`spacing-control-${k}`, `var(--control-${k})`)),
  '  /* Concentric radii: an item inset 4px inside a popover, a cell inset 4px inside a card */',
  decl('radius-item', 'calc(var(--radius-popover) - 4px)'),
  decl('radius-inset', 'calc(var(--radius-card) - 4px)'),
  decl('blur-material', 'var(--material-blur)'),
  '}',
  '',
];
const themeCss = themeLines.join('\n');

// ---------- DTCG JSON, React Native values ----------
const hex = (v: string) => {
  const c = rgba(v);
  const h = formatHex(c);
  const a = c.alpha ?? 1;
  return a < 1
    ? `${h}${Math.round(a * 255)
        .toString(16)
        .padStart(2, '0')}`
    : h;
};
/**
 * A DTCG color value (Design Tokens Format 2025.10): the OKLCH components as authored, plus the sRGB hex fallback
 * the format defines for tools that cannot read OKLCH.
 */
const dtcgColor = (v: string) => {
  const c = parse(v) as Oklch | undefined;
  if (c?.mode !== 'oklch') throw new Error(`Token ${v} is not OKLCH.`);
  return {
    colorSpace: 'oklch',
    components: [c.l, c.c, c.h ?? 'none'],
    alpha: c.alpha ?? 1,
    hex: formatHex(rgba(v)),
  };
};
const dtcg: Record<string, unknown> = {
  $description: 'dtheo/ui design tokens (DTCG format). Generated; source is packages/tokens/src/index.ts.',
};
const native: Record<string, Record<string, Record<string, string>>> = {};
const nativeOklch: Record<string, Record<string, Record<string, string>>> = {};
for (const preset of presets) {
  native[preset.id] = {};
  nativeOklch[preset.id] = {};
  const group: Record<string, unknown> = {};
  for (const [mode, scheme] of Object.entries(preset.modes) as [Mode, ColorScheme][]) {
    group[mode] = Object.fromEntries(
      colorRoles.map((r) => [r, { $type: 'color', $value: dtcgColor(scheme[r]) }]),
    );
    native[preset.id]![mode] = Object.fromEntries(colorRoles.map((r) => [r, hex(scheme[r])]));
    nativeOklch[preset.id]![mode] = Object.fromEntries(colorRoles.map((r) => [r, scheme[r]]));
  }
  group.geometry = Object.fromEntries(
    Object.entries(preset.geometry).map(([k, v]) => [k, { $type: 'dimension', $value: v }]),
  );
  dtcg[preset.id] = group;
}
dtcg.foundation = foundation;
const json = JSON.stringify(dtcg, null, 2) + '\n';
const nativeColors = JSON.stringify(native, null, 2);
const nativeOklchColors = JSON.stringify(nativeOklch, null, 2);
const nativeRadii = JSON.stringify(
  Object.fromEntries(
    presets.map((p) => [
      p.id,
      Object.fromEntries(
        Object.entries(p.geometry)
          .filter(([k]) => k.startsWith('radius'))
          .map(([k, v]) => [k.replace('radius-', ''), Number.parseFloat(v)]),
      ),
    ]),
  ),
  null,
  2,
);
const nativeDoc = `${header.replace('/*', '/**')}\n/** Color roles for code that cannot read CSS variables: React Native, Expo, canvas, image renderers. */\n`;
const colorsDoc =
  '/** sRGB hex, gamut-mapped from OKLCH (8 digits when translucent). React Native StyleSheet cannot parse oklch(). */\n';
const oklchDoc =
  '/** The authored OKLCH values, for anything that reads CSS Color 4: web, Skia, Expo DOM components. */\n';
// The workspace imports the TypeScript; the published package ships plain JS with matching declarations.
const nativeTs = `${nativeDoc}${colorsDoc}export const colors = ${nativeColors} as const;\n\n${oklchDoc}export const oklch = ${nativeOklchColors} as const;\n\nexport const radii = ${nativeRadii} as const;\n`;
const nativeJs = `${nativeDoc}${colorsDoc}export const colors = ${nativeColors};\n\n${oklchDoc}export const oklch = ${nativeOklchColors};\n\nexport const radii = ${nativeRadii};\n`;
const nativeDts = `${nativeDoc}${colorsDoc}export declare const colors: ${nativeColors};\n\n${oklchDoc}export declare const oklch: ${nativeOklchColors};\n\nexport declare const radii: ${nativeRadii};\n`;
const report =
  JSON.stringify(
    rows.map((r) => ({ ...r, ratio: Number(r.ratio.toFixed(2)) })),
    null,
    2,
  ) + '\n';

const outputs: Array<[string, string]> = [
  [resolve(root, 'packages/ui/src/styles/tokens.css'), css + '\n'],
  [resolve(root, 'packages/ui/src/styles/theme.css'), themeCss],
  [resolve(root, 'packages/tokens/dist/tokens.json'), json],
  [resolve(root, 'packages/tokens/dist/native.ts'), nativeTs],
  [resolve(root, 'packages/tokens/dist/native.js'), nativeJs],
  [resolve(root, 'packages/tokens/dist/native.d.ts'), nativeDts],
  [resolve(root, 'packages/tokens/dist/contrast.json'), report],
];

let stale = false;
for (const [file, content] of outputs) {
  if (checkOnly) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== content) {
      stale = true;
      console.error(`Stale output: ${file}. Run \`pnpm tokens\`.`);
    }
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
}
if (!checkOnly) console.log(`\nWrote ${outputs.length} token outputs.`);
if (failures.length || stale) process.exit(1);
